  static Future<void> init() async {
    final prefs = await SharedPreferences.getInstance();
    final savedCode = prefs.getString(_prefLangKey);

    if (savedCode != null) {
      currentLocale.value = Locale(savedCode);
    } else {
      final deviceLocale = ui.PlatformDispatcher.instance.locale;
      if (deviceLocale.languageCode == 'ja') {
        currentLocale.value = const Locale('ja');
      } else if (deviceLocale.languageCode == 'en') {
        currentLocale.value = const Locale('en');
      } else {
        currentLocale.value = const Locale('en');
      }
    }
  }

  static Future<void> changeLocale(String languageCode) async {
    currentLocale.value = Locale(languageCode);
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString(_prefLangKey, languageCode);
  }

  static String tr(String key, [List<dynamic>? args]) {
    final lang = currentLocale.value.languageCode;
    var text =
        _localizedValues[lang]?[key] ?? _localizedValues['en']?[key] ?? _localizedValues['ko']?[key] ?? key;
    if (args != null && args.isNotEmpty) {
      for (var i = 0; i < args.length; i++) {
        text = text.replaceAll('{$i}', args[i].toString());
      }
    }
    return text;
  }
