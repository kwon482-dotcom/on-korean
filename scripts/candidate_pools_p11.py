import json
import os

DATA_FILE = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "assets", "data", "korean_words.json")

def get_existing_db_words():
    with open(DATA_FILE, "r", encoding="utf-8") as f:
        data = json.load(f)
    seen = set(w["word"].strip() for w in data)
    return seen

def filter_candidates(pool, needed_count, seen):
    fresh = []
    for w in pool:
        w_clean = w.strip()
        if w_clean and w_clean not in seen and w_clean not in fresh:
            fresh.append(w_clean)
            seen.add(w_clean)
            if len(fresh) == needed_count:
                break
    return fresh

