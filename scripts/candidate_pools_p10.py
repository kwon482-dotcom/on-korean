def generate_clean_candidate_map():
    seen = get_existing_db_words()
    print(f"[CANDIDATES P10] Initial DB seen words count: {len(seen)}")
    assert len(seen) == 5000, f"Expected 5000 words in DB, got {len(seen)}"
    
    result = {}
    
    cats = [
        ("basics", RAW_BASICS_POOL),
        ("topik1", RAW_TOPIK1_POOL),
        ("topik2", RAW_TOPIK2_POOL),
        ("kdrama", RAW_KDRAMA_POOL),
        ("business", RAW_BUSINESS_POOL)
    ]
    
    for cat_code, pool in cats:
        result[cat_code] = {}
        for p in [1, 2, 3, 4]:
            words = filter_candidates(pool, 50, seen)
            print(f"{cat_code} Part {p}: {len(words)} unique words selected.")
            assert len(words) == 50, f"{cat_code} Part {p} has only {len(words)} words!"
            result[cat_code][p] = words

    out_file = os.path.join(os.path.dirname(os.path.abspath(__file__)), "p10_candidate_map.json")
    with open(out_file, "w", encoding="utf-8") as f:
        json.dump(result, f, ensure_ascii=False, indent=2)
    print(f"[SUCCESS] Wrote all Phase 10 candidate lists to {out_file}")

